@pytest.fixture()
def stub_inception_v3(monkeypatch: pytest.MonkeyPatch) -> None:
    """Monkeypatch the canonical InceptionV3 forward with a deterministic linear map.

    The stub converts an ``(B, 3, H, W)`` image batch into a
    deterministic ``(B, 2048)`` feature vector whose values are in
    a controlled range (``[-2, 2]``). This range mirrors the
    typical activation range of a pretrained InceptionV3 pool3
    layer (which roughly spans ``[-3, 3]``) so the Fréchet
    arithmetic against a small-magnitude reference ``(mu, sigma)``
    pair produces sensible FID values.

    The stub preserves the ``model.fc = nn.Identity()`` replacement
    convention from the canonical constructor so the post-processing
    math in :class:`InceptionV3FIDEvaluator` runs unchanged.
    """
    import torch
    import torch.nn as nn

    class _LinearInceptionStub(nn.Module):
        def __init__(self, **kwargs: Any) -> None:
            super().__init__()
            self.kwargs = dict(kwargs)
            self.fc = nn.Identity()

        def forward(self, x: torch.Tensor) -> torch.Tensor:
            # x: (B, 3, H, W) in [-1, 1] (the canonical harness
            # input range). Reduce spatially to a small per-batch
            # summary, then project to 2048 dims via a small
            # orthonormal-like linear map so the output range is
            # bounded in [-2, 2].
            bsz = int(x.shape[0])
            # Per-batch summary: mean over channels and spatial dims.
            summary = x.to(torch.float32).mean(dim=(1, 2, 3))  # (B,) in [-1, 1]
            # Expand to 2048 via a deterministic, content-dependent
            # projection: the k-th feature is ``summary * cos(k)``
            # (content-driven) plus ``sin(k) / 2048`` (round-stable
            # bias). Magnitudes are bounded.
            k = torch.arange(2048, dtype=torch.float32)
            out = summary.unsqueeze(1) * torch.cos(k).unsqueeze(0) \
                + torch.sin(k).unsqueeze(0) / 2048.0
            return out

        def eval(self) -> "_LinearInceptionStub":
            return super().eval()

    monkeypatch.setattr(
        "torchvision.models.inception_v3",
        lambda **kwargs: _LinearInceptionStub(**kwargs),
        raising=True,
    )


def _seed_round_dir(parent: Path, round_idx: int, n_samples: int = 16) -> Path:
    """Write ``n_samples`` Gaussian-noise PNGs into ``parent/framework_round{r:02d}``.

    The image content (random Gaussian pixel values) is what the
    stubbed InceptionV3 converts into features. Using Gaussian noise
    keeps the test self-contained and fast.
    """
    from PIL import Image

    rd = parent / f"framework_round{round_idx:02d}"
    rd.mkdir(parents=True, exist_ok=True)
    rng = np.random.default_rng(seed=1000 + round_idx)
    for i in range(n_samples):
        # 32x32 noise; the stub aggregates spatially so the
        # round-specific seed is what drives feature variation.
        noise = rng.integers(0, 256, size=(32, 32, 3), dtype=np.uint8)
        Image.fromarray(noise, mode="RGB").save(rd / f"sample_{i:04d}.png")
    return rd


def _seed_baseline_round_dir(parent: Path, round_idx: int, n_samples: int = 16) -> Path:
    """Write ``n_samples`` identical-noise PNGs across rounds (no-improvement baseline).

    The baseline seed is fixed across rounds (seed=9999) so the
    per-round features are essentially constant (modulo integer
    round-trip artefacts). This is the "algorithm never improved"
    oracle.
    """
    from PIL import Image

    rd = parent / f"baseline_round{round_idx:02d}"
    rd.mkdir(parents=True, exist_ok=True)
    rng = np.random.default_rng(seed=9999)  # fixed across rounds
    for i in range(n_samples):
        noise = rng.integers(0, 256, size=(32, 32, 3), dtype=np.uint8)
        Image.fromarray(noise, mode="RGB").save(rd / f"sample_{i:04d}.png")
    return rd


def _build_canonical_reference_stats(
    *,
    feature_dim: int = 2048,
    seed: int = 42,
    mu_scale: float = 0.5,
    sigma_scale: float = 0.05,
) -> tuple[np.ndarray, np.ndarray]:
    """Build a synthetic canonical reference stats pair.

    Returns ``(mu, sigma)`` where ``mu`` has shape ``(feature_dim,)``
    and ``sigma`` has shape ``(feature_dim, feature_dim)``. Both are
    in a controlled magnitude range (``mu ~ [-0.5, 0.5]``,
    ``sigma diagonal ~ [0, 0.05]``) so the Fréchet arithmetic
    against bounded InceptionV3 stub features produces sensible
    FID values.

    The covariance is rank-K PSD (``K=8``) plus a small diagonal
    ridge for PSD safety.
    """
    rng = np.random.default_rng(seed=int(seed))
    mu = rng.standard_normal(int(feature_dim)).astype(np.float64) * float(mu_scale)
    K = 8
    V = rng.standard_normal((int(feature_dim), K)).astype(np.float64)
    s = rng.uniform(0.1, 0.5, size=K).astype(np.float64) * float(sigma_scale)
    sigma = (V * s) @ V.T
    sigma = 0.5 * (sigma + sigma.T)
    sigma = sigma + 1e-4 * np.eye(int(feature_dim), dtype=np.float64)
    return mu, sigma


def _extract_round_features(
    image_eval: Any,
    round_dir: Path,
    *,
    reference_mu: np.ndarray,
    feature_dim: int,
    image_target_size: int = 32,
    fid_batch_size: int = 8,
    alpha_blend: float = 1.0,
) -> np.ndarray:
    """Extract InceptionV3 pool3 features for one round.

    ``alpha_blend`` simulates the per-round mixture toward the
    reference: ``features = alpha * round_features + (1 - alpha)
    * reference_features``. This is the synthetic analog of the
    framework's per-round "improvement" trajectory.
    """
    # discover_samples / load_images_as_tensor are not used here
    # because the stubbed InceptionV3 accepts PIL arrays directly;
    # we feed the model raw pixel arrays via torch.
    import torch

    # Read PNGs back as numpy arrays.
    pngs = sorted(round_dir.glob("sample_*.png"))
    from PIL import Image
    arrays: list[np.ndarray] = []
    for p in pngs:
        with Image.open(p) as img:
            arr = np.asarray(img.convert("RGB"), dtype=np.float32) / 255.0
            arr = (arr * 2.0) - 1.0
            arr = arr.transpose(2, 0, 1)  # (3, H, W)
            arrays.append(arr)
    if not arrays:
        return np.zeros((0, int(feature_dim)), dtype=np.float32)
    stacked = np.stack(arrays, axis=0).astype(np.float32)
    feats = image_eval.extract_inception_features_for_image_eval(
        stacked,
        device=torch.device("cpu"),
        batch_size=int(fid_batch_size),
    )
    # Apply alpha-blend toward reference mean (broadcast mu to row).
    feats_f64 = feats.astype(np.float64, copy=False)
    if alpha_blend < 1.0:
        target_rows = np.broadcast_to(reference_mu, feats_f64.shape).copy()
        feats_f64 = alpha_blend * feats_f64 + (1.0 - alpha_blend) * target_rows
    return feats_f64


@dataclass(frozen=True)
class _RoundResult:
    """Per-round FID bookkeeping."""

    round_index: int
    n_samples: int
    fid: float


