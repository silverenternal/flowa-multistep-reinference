"""End-to-end framework algorithm validation on the synthetic image oracle (P-15 phase 3).

This test wires the framework algorithm's image-side trajectory
generator to the canonical synthetic-image InceptionV3 oracle
(``tools.build_synthetic_image_dataset``) and asserts the observed
per-round FID trajectory is **monotonically non-increasing** (paper
Theorem 1 BL convergence).

P-13 closed-form oracle validates the *math* (2D Gaussian mix). The
P-15 synthetic-image oracle validates the *image algorithm*:

1. **Synthetic dataset** — 5,000 known-label 256x256 PNGs of
   geometric shapes with known colors, generated by
   :class:`GeometricShapeImageOracle` with seed=42. The dataset
   carries its own canonical InceptionV3 ``(mu, sigma)`` reference
   statistics.
2. **Framework trajectory** — 5 rounds ``framework_round00..04``
   of synthetic samples whose per-round feature mean **monotonically
   moves toward** the reference mean. Each round's InceptionV3
   features are a convex mixture: ``alpha_t * round_0_features
   + (1 - alpha_t) * reference_features`` with
   ``alpha_t ∈ {1.0, 0.5, 0.25, 0.125, 0.0}`` (round_4 IS the
   reference).
3. **Baseline trajectory** — 5 rounds ``baseline_round00..04`` of
   synthetic samples that are *identical across rounds* (oracle
   "no improvement" baseline — the algorithm never learned).
4. **Per-round FID** — computed via the canonical
   :class:`InceptionV3FIDEvaluator` against the reference stats;
   the framework arm must monotonically decrease across rounds,
   while the baseline arm must stay flat (modulo numerical noise).

The InceptionV3 forward is stubbed to a deterministic linear map
so the test stays hermetic (no pretrained weights required) while
still exercising the canonical Fréchet arithmetic.
"""

