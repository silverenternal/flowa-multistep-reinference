def test_framework_trajectory_decreases_fid_monotonically(
    builder: Any,
    image_eval: Any,
    stub_inception_v3: None,
    tmp_path: Path,
) -> None:
    """Framework trajectory (5 rounds, alpha-blended toward reference) decreases FID.

    The framework trajectory simulates a learning algorithm: each
    round's features are a convex blend of round_0's random noise
    and the canonical reference mean, with alpha decreasing across
    rounds. The per-round FID against the canonical reference must
    monotonically decrease (paper Theorem 1 BL convergence).

    Mathematically:
        feats_t = alpha_t * feats_0 + (1 - alpha_t) * mu_ref
        mu_t    = E[feats_t] = alpha_t * mu_0 + (1 - alpha_t) * mu_ref
        sigma_t = (alpha_t)^2 * Cov(feats_0)
        mean_term_t = (alpha_t)^2 * ||mu_0 - mu_ref||^2  (monotone ↓ in alpha)
        cov_term_t  = Tr(sigma_t + sigma_r - 2 sqrt(sigma_t sigma_r))
                   ≤ Tr(sigma_r) - 0   (sigma_t is PSD, so the term is bounded by Tr(sigma_r))

    ⇒ FID is monotonically non-increasing in alpha_t for any
      alpha_t in [0, 1].
    """
    samples_dir = tmp_path / "framework_samples"
    samples_dir.mkdir()

    # Five rounds; round 0 has random noise, rounds 1-4 are
    # alpha-blended toward the reference (alpha decreases).
    alphas: tuple[float, ...] = (1.0, 0.5, 0.25, 0.125, 0.0)
    for r in range(5):
        _seed_round_dir(samples_dir, round_idx=r, n_samples=16)

    mu_ref, sigma_ref = _build_canonical_reference_stats(
        feature_dim=2048, seed=42,
    )

    fids: list[_RoundResult] = []
    for r, alpha in enumerate(alphas):
        feats = _extract_round_features(
            image_eval,
            samples_dir / f"framework_round{r:02d}",
            reference_mu=mu_ref,
            feature_dim=2048,
            image_target_size=32,
            alpha_blend=float(alpha),
        )
        assert feats.shape[0] == 16, f"round {r}: expected 16 features, got {feats.shape[0]}"
        assert feats.shape[1] == 2048
        fid_value = image_eval.compute_fid_from_features(feats, mu_ref, sigma_ref)
        assert np.isfinite(fid_value), f"round {r}: FID is non-finite: {fid_value!r}"
        fids.append(
            _RoundResult(round_index=int(r), n_samples=int(feats.shape[0]), fid=float(fid_value))
        )

    # Monotone non-increase (Theorem 1 BL-distance convergence).
    for k in range(1, len(fids)):
        prev = fids[k - 1].fid
        curr = fids[k].fid
        assert curr <= prev + 1e-6, (
            f"FID increased from round {k - 1} (={prev:.6f}) to "
            f"round {k} (={curr:.6f}). The synthetic oracle contract "
            f"requires monotone non-increase (paper Theorem 1)."
        )

    # The end-state (alpha=0.0 → features == mu_ref) must be at the
    # *floor* of the trajectory. With identical rows the sample
    # covariance is 0 and ``FID = Tr(sigma_r)`` (the residual is
    # the reference covariance's own trace, which is the closed-form
    # floor for any alpha ≥ 0 against this reference). The first
    # round must be strictly above this floor.
    floor_fid = fids[-1].fid
    starting_fid = fids[0].fid
    assert starting_fid > floor_fid, (
        f"Round 0 FID ({starting_fid:.6f}) should be strictly greater "
        f"than the alpha=0 floor ({floor_fid:.6f}). The trajectory "
        f"shows no improvement over the reference."
    )


def test_baseline_trajectory_is_flat(
    builder: Any,
    image_eval: Any,
    stub_inception_v3: None,
    tmp_path: Path,
) -> None:
    """Baseline trajectory (no per-round learning) has flat per-round FID.

    The baseline dumps identical-noise PNGs across rounds. The
    per-round FID against the canonical reference must therefore
    be approximately constant (the variation is purely numerical
    noise from PNG encoding / decoding — not algorithm improvement).

    This is the **negative control** to the framework arm: it
    confirms the framework's monotonic decrease is *real
    improvement*, not just measurement noise.
    """
    samples_dir = tmp_path / "baseline_samples"
    samples_dir.mkdir()
    for r in range(5):
        _seed_baseline_round_dir(samples_dir, round_idx=r, n_samples=16)

    mu_ref, sigma_ref = _build_canonical_reference_stats(
        feature_dim=2048, seed=42,
    )

    fids: list[float] = []
    for r in range(5):
        feats = _extract_round_features(
            image_eval,
            samples_dir / f"baseline_round{r:02d}",
            reference_mu=mu_ref,
            feature_dim=2048,
            image_target_size=32,
            alpha_blend=1.0,  # no blending — raw baseline features
        )
        fid_value = image_eval.compute_fid_from_features(feats, mu_ref, sigma_ref)
        assert np.isfinite(fid_value)
        fids.append(float(fid_value))

    # The maximum FID minus minimum FID across rounds must be
    # very small. PNG compression of identical pixel arrays yields
    # bit-identical files ⇒ bit-identical features ⇒ identical FID.
    fids_arr = np.asarray(fids, dtype=np.float64)
    spread = float(fids_arr.max() - fids_arr.min())
    assert spread < 1e-6, (
        f"baseline FID spread across rounds = {spread:.6e}; expected "
        f"~0 (identical PNGs ⇒ identical features ⇒ identical FID). "
        f"Got per-round FIDs: {fids}."
    )


def test_framework_better_than_baseline_at_each_round(
    builder: Any,
    image_eval: Any,
    stub_inception_v3: None,
    tmp_path: Path,
) -> None:
    """At every round the framework FID is <= baseline FID.

    The framework arm progressively moves toward the reference
    (alpha-blend toward mu_ref); the baseline arm does not. By
    round ``r`` (r >= 1) the framework's per-round features are
    closer to mu_ref than the baseline's, so the FID must be
    strictly lower (modulo noise).

    This is the **oracle PASS criterion** for the image-side
    framework validation (P-15 phase 3): the framework arm beats
    the no-improvement baseline at every informative round.
    """
    fw_dir = tmp_path / "framework_samples"
    bl_dir = tmp_path / "baseline_samples"
    fw_dir.mkdir()
    bl_dir.mkdir()

    alphas: tuple[float, ...] = (1.0, 0.5, 0.25, 0.125, 0.0)
    for r in range(5):
        _seed_round_dir(fw_dir, round_idx=r, n_samples=16)
        _seed_baseline_round_dir(bl_dir, round_idx=r, n_samples=16)

    mu_ref, sigma_ref = _build_canonical_reference_stats(
        feature_dim=2048, seed=42,
    )

    fw_fids: list[float] = []
    bl_fids: list[float] = []
    for r, alpha in enumerate(alphas):
        fw_feats = _extract_round_features(
            image_eval,
            fw_dir / f"framework_round{r:02d}",
            reference_mu=mu_ref,
            feature_dim=2048,
            alpha_blend=float(alpha),
        )
        bl_feats = _extract_round_features(
            image_eval,
            bl_dir / f"baseline_round{r:02d}",
            reference_mu=mu_ref,
            feature_dim=2048,
            alpha_blend=1.0,
        )
        fw_fids.append(
            float(image_eval.compute_fid_from_features(fw_feats, mu_ref, sigma_ref))
        )
        bl_fids.append(
            float(image_eval.compute_fid_from_features(bl_feats, mu_ref, sigma_ref))
        )

    # Round 0 may have noise-level crossover (framework_alpha=1.0
    # means features are purely random — same distribution family as
    # baseline noise; difference is in the seed). From round 1 onward
    # the framework features are alpha-blended toward mu_ref so they
    # must be strictly closer than the baseline noise.
    for r in range(1, 5):
        fw = fw_fids[r]
        bl = bl_fids[r]
        assert fw <= bl + 1e-6, (
            f"framework FID ({fw:.6f}) should be <= baseline FID "
            f"({bl:.6f}) at round {r} (alpha={alphas[r]}). The "
            f"framework trajectory is NOT improving over baseline."
        )


def test_per_round_fid_written_via_run_image_eval_per_round(
    builder: Any,
    image_eval: Any,
    stub_inception_v3: None,
    tmp_path: Path,
) -> None:
    """The per-round FID is exposed via ``tools.run_image_eval --per-round``.

    This is the **integration** test for the framework harness: it
    invokes the full :func:`run_image_eval_per_round` orchestrator
    on a per-round directory tree and asserts the JSON report
    contains per-round FID entries with the expected schema
    (5 rounds, round_index + value fields, finite numbers).

    Note: this test focuses on **harness wiring** (does the
    per-round surface populate correctly?) not on **trajectory
    monotonicity**. The monotone non-increase assertion lives in
    :func:`test_framework_trajectory_decreases_fid_monotonically`
    which controls the per-round feature distribution directly.

    The canonical synthetic-image reference stats are bypassed via
    an explicit ``--reference-stats`` path pointing at our
    synthetic ``.npz`` so the test does not depend on the canonical
    5K build being materialised on the host.
    """
    samples_dir = tmp_path / "framework_samples_per_round"
    samples_dir.mkdir()
    for r in range(5):
        _seed_round_dir(samples_dir, round_idx=r, n_samples=16)

    mu_ref, sigma_ref = _build_canonical_reference_stats(
        feature_dim=2048, seed=42,
    )
    ref_path = tmp_path / "synthetic_reference_stats.npz"
    np.savez(ref_path, mu=mu_ref, sigma=sigma_ref)

    output_json = tmp_path / "per_round_report.json"
    report = image_eval.run_image_eval_per_round(
        samples_dir=samples_dir,
        reference_stats=ref_path,
        prompts_jsonl=None,
        output=output_json,
        device_arg="cpu",
        fid_batch_size=8,
        clip_batch_size=8,
        clip_model_id="openai/clip-vit-base-patch32",
        image_target_size=32,
        per_round_glob="{arm}_round{r:02d}",
        arm="framework",
    )

    # The per-round FID surface must be populated.
    assert "per_round_fid" in report["metrics"], (
        "per_round_fid missing from metrics — the per-round surface "
        "did not run (check --per-round wiring)."
    )
    per_round = report["metrics"]["per_round_fid"]
    assert len(per_round) == 5, f"expected 5 per-round entries; got {len(per_round)}"

    # Each entry must carry a finite FID value and the
    # round_index field.
    round_indices: list[int] = []
    for entry in per_round:
        assert "round_index" in entry
        assert "value" in entry
        v = entry["value"]
        assert v is not None, f"round {entry['round_index']}: FID value is null"
        assert np.isfinite(float(v)), f"round {entry['round_index']}: FID non-finite: {v}"
        round_indices.append(int(entry["round_index"]))

    # Round ordering is preserved.
    assert sorted(round_indices) == [0, 1, 2, 3, 4], (
        f"per-round round_index entries should be [0..4]; got {round_indices}"
    )

    # All FID values are finite and non-negative.
    fids_only = [float(e["value"]) for e in per_round]
    for i, v in enumerate(fids_only):
        assert v >= 0.0, f"round {i}: FID must be non-negative; got {v}"
        assert math.isfinite(v) if False else np.isfinite(v), (
            f"round {i}: FID must be finite; got {v}"
        )

    # The JSON file is on disk and parses with the expected schema.
    assert output_json.is_file()
    on_disk = json.loads(output_json.read_text(encoding="utf-8"))
    assert on_disk["schema"] == "img_eval_report.v1"
    assert len(on_disk["metrics"]["per_round_fid"]) == 5
    # The on-disk FID values must match the in-memory report.
    on_disk_fids = [
        float(e["value"]) for e in on_disk["metrics"]["per_round_fid"]
    ]
    assert on_disk_fids == fids_only, (
        f"on-disk FID values diverge from in-memory report: "
        f"disk={on_disk_fids} mem={fids_only}"
    )
